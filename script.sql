create function create_patient_search_hash_insert() returns trigger
    language plpgsql
as
$$BEGIN 
	NEW.patientsearchhash := CONCAT(lower(TRIM(NEW.lastname)), lower(TRIM(NEW.firstname)), lower(TRIM(NEW.mrn)), NEW.patientid);
	INSERT INTO mtbtracking.mtb_newpatient_debug (patientid, lastname, firstname, mrn, patienthash) VALUES (NEW.patientid,NEW.lastname,NEW.firstname,NEW.mrn,CONCAT(lower(TRIM(NEW.lastname)), lower(TRIM(NEW.firstname)), lower(TRIM(NEW.mrn)), NEW.patientid));
   RETURN NEW; 
END;$$;

alter function create_patient_search_hash_insert() owner to justin;

create function create_patient_search_hash() returns trigger
    language plpgsql
as
$$
BEGIN
	IF CONCAT(lower(OLD.lastname), lower(OLD.firstname), lower(OLD.mrn), OLD.patientid) != CONCAT(lower(NEW.lastname), lower(NEW.firstname), lower(NEW.mrn), NEW.patientid) OR NEW.patientsearchhash IS NULL THEN
		UPDATE mtbtracking.patientdata
		SET patientsearchhash = CONCAT(lower(NEW.lastname), lower(NEW.firstname), lower(NEW.mrn), NEW.patientid)
		WHERE OLD.patientid = patientid;
	END IF;
    RETURN NEW;
END;
$$;

alter function create_patient_search_hash() owner to justin;

create trigger after_update_patient_searchhash_trigger
    after update
    on patientdata
    for each row
execute procedure create_patient_search_hash();


