create view lookupsite(edition, topographycode, description, searchhash, storevalue) as
SELECT cdtopography.edition,
       btrim(cdtopography.topographycode::text)                                                                AS topographycode,
       btrim(cdtopography.description::text)                                                                   AS description,
       concat(btrim(cdtopography.topographycode::text),
              btrim(cdtopography.description::text))                                                           AS searchhash,
       concat_ws(' - '::text, btrim(cdtopography.topographycode::text),
                 btrim(cdtopography.description::text))                                                        AS storevalue
FROM cpdmsglobal.cdtopography
WHERE cdtopography.edition = '3'::bpchar;


create view lookuphistology
            (edition, histologycode, behaviorcode, behaviorcodedescription, histology, searchhash, storevalue,
             source) as
SELECT comp.edition,
       comp.histologycode,
       comp.behaviorcode,
       comp.behaviorcodedescription,
       comp.histology,
       comp.searchhash,
       comp.storevalue,
       comp.source
FROM (SELECT hist.edition,
             btrim(hist.histologycode::text)                                                                       AS histologycode,
             btrim(hist.behaviorcode::text)                                                                        AS behaviorcode,
             btrim(lu_bc.type::text)                                                                               AS behaviorcodedescription,
             btrim(hist.description::text)                                                                         AS histology,
             concat(btrim(hist.histologycode::text), btrim(hist.description::text),
                    'CPDMS')                                                                                       AS searchhash,
             concat(btrim(hist.histologycode::text), '/', hist.behaviorcode, ' - ',
                    btrim(hist.description::text))                                                                 AS storevalue,
             'CPDMS'::text                                                                                         AS source
      FROM cpdmsglobal.cdhistology hist
               LEFT JOIN cpdmsglobal.cdbehaviorcodes lu_bc ON lu_bc.code = hist.behaviorcode
      UNION ALL
      SELECT 'CUSTOM'::bpchar                                                                            AS edition,
             btrim(chist.code::text)                                                                     AS histologycode,
             btrim(chist.behavior::text)                                                                 AS behaviorcode,
             ''::text                                                                                    AS behaviorcodedescription,
             btrim(chist.description::text)                                                              AS histology,
             concat(btrim(chist.code::text), btrim(chist.description::text), 'CUSTOM')                   AS searchhash,
             concat(btrim(chist.code::text), '/', chist.behavior, ' - ', btrim(chist.description::text)) AS storevalue,
             'CUSTOM'::text                                                                              AS source
      FROM mtbtracking.customhistology chist) comp
WHERE comp.edition = ANY (ARRAY ['3'::bpchar, 'CUSTOM'::bpchar])
ORDER BY comp.edition, comp.histologycode, comp.behaviorcode;



create view druglist(value, display) as
SELECT a.value,
       a.display
FROM (SELECT DISTINCT recommendationdata.recommendation AS value,
                      recommendationdata.recommendation AS display
      FROM mtbtracking.recommendationdata) a
WHERE char_length(a.value::text) <> 0
ORDER BY a.value;



